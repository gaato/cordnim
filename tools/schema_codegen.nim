  node.requireObject("document")
  if not node.hasKey(key) or node[key].kind != JInt:
    fail "missing integer field: " & key
  node[key].getInt

proc sortedKeys(node: JsonNode): seq[string] =
  node.requireObject("value")
  for key, _ in node.fields:
    result.add key
  result.sort

proc overlayFailure(message: string) {.noreturn.} =
  raise newException(OverlayError, message)

proc requireOverlayObject(node: JsonNode; description: string) =
  if node.isNil or node.kind != JObject:
    overlayFailure(description & " must be a JSON object")

proc validateOverlayKeys(
    node: JsonNode; allowed: openArray[string]; description: string
) =
  node.requireOverlayObject(description)
  for key, _ in node.fields:
    if key notin allowed:
      overlayFailure(description & " has unknown field: " & key)

proc overlayString(
    node: JsonNode; key, description: string
): string =
  node.requireOverlayObject(description)
  if not node.hasKey(key) or node[key].kind != JString:
    overlayFailure(description & " requires string field: " & key)
  result = node[key].getStr
  if result.len == 0:
    overlayFailure(description & " field must not be empty: " & key)

proc overlayTargets(node: JsonNode; description: string): seq[string] =
  node.requireOverlayObject(description)
  if not node.hasKey("target"):
    overlayFailure(description & " requires field: target")
  let target = node["target"]
  case target.kind
  of JString:
    if target.getStr.len == 0:
      overlayFailure(description & " target must not be empty")
    result.add target.getStr
  of JArray:
    if target.len == 0:
      overlayFailure(description & " target array must not be empty")
    for index in 0..<target.len:
      if target[index].kind != JString or target[index].getStr.len == 0:
        overlayFailure(
          description & " target array requires non-empty strings at index " &
            $index
        )
      result.add target[index].getStr
  else:
    overlayFailure(description & " target must be a string or string array")

proc overlayInt(node: JsonNode; key, description: string): int =
