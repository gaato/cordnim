proc decodePointerSegment(value: string): string =
  var index = 0
  while index < value.len:
    if value[index] == '~':
      if index + 1 >= value.len or value[index + 1] notin {'0', '1'}:
        overlayFailure("malformed JSON Pointer escape in selector segment")
      if value[index + 1] == '0':
        result.add '~'
      else:
        result.add '/'
      index += 2
    else:
      result.add value[index]
      inc index

proc parseSelectorAlternative(value: string): Selector =
  if value.len == 0 or value.strip != value:
    overlayFailure("overlay selector alternatives must not be empty or padded")

  let rawSegments = if value.startsWith("#/"):
    value[2..^1].split('/')
  elif value.startsWith("**/"):
    value.split('/')
  else:
    overlayFailure(
      "selector must start with '#/' or '**/': " & value
    )

  result.source = value
  for rawSegment in rawSegments:
    if rawSegment.len == 0:
      overlayFailure("selector contains an empty segment: " & value)
    if rawSegment == "**":
      result.segments.add rawSegment
    else:
      if rawSegment.contains("**") or rawSegment.count('*') > 1:
        overlayFailure("malformed wildcard segment in selector: " & value)
      result.segments.add rawSegment.decodePointerSegment

proc parseSelector(value: string): seq[Selector] =
  for alternative in value.split('|'):
    result.add alternative.parseSelectorAlternative
  if result.len == 0:
    overlayFailure("overlay selector must contain an alternative")

func segmentMatches(pattern, value: string): bool =
  let wildcard = pattern.find('*')
  if wildcard < 0:
    return pattern == value
  let prefix = pattern[0..<wildcard]
  let suffix = if wildcard + 1 < pattern.len:
    pattern[wildcard + 1..^1]
  else:
    ""
  value.len >= prefix.len + suffix.len and value.startsWith(prefix) and
    value.endsWith(suffix)

func selectorMatchesAt(
    pattern, value: openArray[string]; patternIndex, valueIndex: int
): bool =
  if patternIndex == pattern.len:
    return valueIndex == value.len
  if pattern[patternIndex] == "**":
    for nextIndex in valueIndex..value.len:
      if selectorMatchesAt(
          pattern, value, patternIndex + 1, nextIndex
      ):
        return true
    return false
  valueIndex < value.len and
    segmentMatches(pattern[patternIndex], value[valueIndex]) and
    selectorMatchesAt(pattern, value, patternIndex + 1, valueIndex + 1)

func matches(selector: Selector; location: JsonLocation): bool =
  selectorMatchesAt(selector.segments, location.segments, 0, 0)

func scalarWireSchemaMatches(node: JsonNode; allowNull: bool): bool =
  if node.isNil or node.kind != JObject or not node.hasKey("type"):
    return false

  var hasWireType = false
  proc validType(value: JsonNode): bool =
    if value.kind != JString:
      return false
    case value.getStr
    of "string", "integer":
      hasWireType = true
      true
    of "null":
      allowNull
    else:
      false

  let schemaType = node["type"]
  case schemaType.kind
  of JString:
    result = validType(schemaType) and hasWireType
  of JArray:
    if schemaType.len == 0:
      return false
    result = true
    for value in schemaType.items:
      if not validType(value):
        result = false
    result = result and hasWireType
  else:
    result = false

func objectSchemaMatches(node: JsonNode): bool =
  node != nil and node.kind == JObject and node.hasKey("type") and
    node["type"].kind == JString and node["type"].getStr == "object" and
    node.hasKey("properties") and node["properties"].kind == JObject

func objectSchemaHasProperties(
    node: JsonNode; propertyNames: openArray[string]
): bool =
  if not objectSchemaMatches(node):
    return false
  for propertyName in propertyNames:
    if not node["properties"].hasKey(propertyName):
      return false
  true

func openEnumMatches(node: JsonNode): bool =
  if node.isNil or node.kind != JArray or node.len == 0:
    return false
  var wireKind = JNull
  for value in node.items:
    if value.kind notin {JInt, JString}:
      return false
    if wireKind == JNull:
      wireKind = value.kind
    elif value.kind != wireKind:
      return false
  true

func componentSchemaMatches(node: JsonNode): bool =
  objectSchemaHasProperties(node, ["type"]) and
    node["properties"]["type"].kind == JObject and
    node["properties"]["type"].hasKey("enum") and
    openEnumMatches(node["properties"]["type"]["enum"])

func observedShape(node: JsonNode): string =
  if node.isNil:
    return "nil"
  case node.kind
  of JObject:
    if node.hasKey("type"):
      "OpenAPI schema with type " & $node["type"]
    else:
      "OpenAPI object without a type"
  of JArray:
    "JSON array with " & $node.len & " item(s)"
  of JString:
    "JSON string '" & node.getStr & "'"
  else:
    "JSON " & $node.kind

proc validateSemanticNode(
    rule: OverlayRule; selector: string; location: JsonLocation
) =
  let valid = case rule.semantic
    of OverlaySemanticKind.Snowflake:
      scalarWireSchemaMatches(location.node, allowNull = false)
    of OverlaySemanticKind.ExtensibleBits:
      scalarWireSchemaMatches(location.node, allowNull = true)
    of OverlaySemanticKind.PatchObject:
      objectSchemaMatches(location.node)
    of OverlaySemanticKind.IrreversibleComponentsV2Transition:
      objectSchemaHasProperties(location.node, ["components", "flags"])
    of OverlaySemanticKind.LegalComponentTree,
        OverlaySemanticKind.ModalLabelTree:
      componentSchemaMatches(location.node)
    of OverlaySemanticKind.ExclusiveUnion:
      location.node != nil and location.node.kind == JString and
        location.node.getStr == "oneOf"
    of OverlaySemanticKind.OpenEnum:
      openEnumMatches(location.node)

  if not valid:
    overlayFailure(
      "semantic '" & rule.semantic.semanticWire & "' selector '" &
        selector & "' matched incompatible node " & location.pointer &
        "; expected " & semanticExpectedShapes[rule.semantic] &
        "; observed " & location.node.observedShape
    )

func encodePointerSegment(value: string): string =
  value.replace("~", "~0").replace("/", "~1")

func toJsonPointer(segments: openArray[string]): string =
  result = "#"
  for segment in segments:
    result.add '/'
    result.add segment.encodePointerSegment

proc collectJsonLocations(
    node: JsonNode; segments: var seq[string]; locations: var seq[JsonLocation]
) =
  var copiedSegments: seq[string]
  for segment in segments:
    copiedSegments.add segment
  locations.add JsonLocation(
    pointer: copiedSegments.toJsonPointer,
    segments: copiedSegments,
    node: node,
  )

  case node.kind
  of JObject:
    var keys: seq[string]
    for key, _ in node.fields:
      keys.add key
    keys.sort
    for key in keys:
      segments.add key
      collectJsonLocations(node[key], segments, locations)
      segments.setLen(segments.len - 1)
  of JArray:
    for index in 0..<node.len:
      segments.add $index
      collectJsonLocations(node[index], segments, locations)
      segments.setLen(segments.len - 1)
  else:
    discard

func descriptorSchemaName(segments: openArray[string]): string =
  if segments.len >= 3 and segments[0] == "components" and
      segments[1] == "schemas":
    segments[2]
  else:
    ""

func descriptorPropertyName(segments: openArray[string]): string =
  if segments.len >= 2:
    for index in 0..<(segments.len - 1):
      if segments[index] == "properties":
        result = segments[index + 1]

proc parseOverlayConstraints(node: JsonNode): OverlayConstraints =
  const allowed = [
    "preserveUnknownObjectFields",
    "preserveUnknownEnumValues",
    "preserveUnknownFlagBits",
    "treatOptionalAndNullableSeparately",
    "componentsV2Irreversible",
    "maximumMessageComponents",
    "legacyAndV2MessageFieldsExclusive",
  ]
  node.validateOverlayKeys(allowed, "overlay constraints")
  result.preserveUnknownObjectFields = node.overlayBool(
    "preserveUnknownObjectFields", "overlay constraints"
  )
  result.preserveUnknownEnumValues = node.overlayBool(
    "preserveUnknownEnumValues", "overlay constraints"
  )
  result.preserveUnknownFlagBits = node.overlayBool(
    "preserveUnknownFlagBits", "overlay constraints"
  )
  result.treatOptionalAndNullableSeparately = node.overlayBool(
    "treatOptionalAndNullableSeparately", "overlay constraints"
  )
  result.componentsV2Irreversible = node.overlayBool(
    "componentsV2Irreversible", "overlay constraints"
  )
  result.maximumMessageComponents = node.overlayInt(
    "maximumMessageComponents", "overlay constraints"
  )
  result.legacyAndV2MessageFieldsExclusive = node.overlayBool(
    "legacyAndV2MessageFieldsExclusive", "overlay constraints"
  )
  if result.maximumMessageComponents <= 0:
    overlayFailure("maximumMessageComponents must be positive")
  for invariant in [
    ("preserveUnknownObjectFields",
      result.preserveUnknownObjectFields),
    ("preserveUnknownEnumValues", result.preserveUnknownEnumValues),
    ("preserveUnknownFlagBits", result.preserveUnknownFlagBits),
    ("treatOptionalAndNullableSeparately",
      result.treatOptionalAndNullableSeparately),
    ("componentsV2Irreversible", result.componentsV2Irreversible),
    ("legacyAndV2MessageFieldsExclusive",
      result.legacyAndV2MessageFieldsExclusive),
  ]:
    if not invariant[1]:
      overlayFailure(
        "overlay constraint " & invariant[0] &
          " must be true for the current implementation"
      )
  if result.maximumMessageComponents != 40:
    overlayFailure(
      "overlay constraint maximumMessageComponents must be 40 for the " &
        "current implementation"
    )

proc applySemanticOverlay*(
    spec, overlay: JsonNode
): SemanticOverlayPlan =
  ## Validates and applies every semantic rule to concrete OpenAPI locations.
  ##
  ## Every selector alternative must match. Multiple rules may not own the
  ## same location, even if their semantic declarations are identical.
  const topLevelKeys = ["revision", "description", "rules", "constraints"]
  const ruleKeys = ["target", "semantic", "representation", "reason"]

  spec.requireOverlayObject("OpenAPI document")
  overlay.validateOverlayKeys(topLevelKeys, "semantic overlay")
  result.revision = overlay.overlayInt("revision", "semantic overlay")
  if result.revision <= 0:
    overlayFailure("semantic overlay revision must be positive")
  result.description = overlay.overlayString(
    "description", "semantic overlay"
  )
  if not overlay.hasKey("rules") or overlay["rules"].kind != JArray:
    overlayFailure("semantic overlay requires array field: rules")
  if overlay["rules"].len == 0:
    overlayFailure("semantic overlay must contain at least one rule")
  if not overlay.hasKey("constraints"):
    overlayFailure("semantic overlay requires object field: constraints")
  result.constraints = parseOverlayConstraints(overlay["constraints"])

  var selectors: seq[seq[Selector]]
  var targets = initHashSet[string]()
  for index in 0..<overlay["rules"].len:
    let node = overlay["rules"][index]
    let description = "semantic overlay rule " & $index
    node.validateOverlayKeys(ruleKeys, description)
    let targetValues = node.overlayTargets(description)
    var ruleSelectors: seq[Selector]
    for targetValue in targetValues:
      for selector in targetValue.parseSelector:
        ruleSelectors.add selector
    ruleSelectors.sort(proc(left, right: Selector): int =
      cmp(left.source, right.source))
    for selectorIndex in 1..<ruleSelectors.len:
      if ruleSelectors[selectorIndex - 1].source ==
          ruleSelectors[selectorIndex].source:
        overlayFailure(
          description & " repeats selector: " &
            ruleSelectors[selectorIndex].source
        )
    var targetParts: seq[string]
    for selector in ruleSelectors:
      targetParts.add selector.source
    let target = targetParts.join("|")
    if target in targets:
      overlayFailure("duplicate overlay target: " & target)
    targets.incl target
    let semantic = parseSemantic(node.overlayString("semantic", description))
    let representation = parseRepresentation(
      node.overlayString("representation", description)
    )
    validateSemanticPair(semantic, representation)
    result.rules.add OverlayRule(
      target: target,
      semantic: semantic,
      representation: representation,
      reason: node.overlayString("reason", description),
    )
    selectors.add ruleSelectors

  var segments: seq[string]
  var locations: seq[JsonLocation]
  collectJsonLocations(spec, segments, locations)
  var ownerByPointer = initTable[string, int]()

  for ruleIndex in 0..<result.rules.len:
    var matchesByPointer = initTable[string, JsonLocation]()
    for selector in selectors[ruleIndex]:
      var alternativeMatches = 0
      for location in locations:
        if selector.matches(location):
          validateSemanticNode(
            result.rules[ruleIndex], selector.source, location
          )
          inc alternativeMatches
          if matchesByPointer.hasKey(location.pointer):
            overlayFailure(
              "selector alternatives overlap at " & location.pointer &
                " in target " & result.rules[ruleIndex].target
            )
          matchesByPointer[location.pointer] = location
      if alternativeMatches == 0:
        overlayFailure(
          "selector alternative matched no OpenAPI location: " &
            selector.source
        )

    var pointers: seq[string]
    for pointer in matchesByPointer.keys:
      pointers.add pointer
    pointers.sort
    result.rules[ruleIndex].matchCount = pointers.len

    for pointer in pointers:
      if ownerByPointer.hasKey(pointer):
        let previousIndex = ownerByPointer[pointer]
        let previous = result.rules[previousIndex]
        let current = result.rules[ruleIndex]
        if previous.semantic == current.semantic and
            previous.representation == current.representation:
          overlayFailure(
            "duplicate semantic match at " & pointer & " from rules " &
              $previousIndex & " and " & $ruleIndex
          )
        overlayFailure(
          "conflicting semantic match at " & pointer & " from rules " &
            $previousIndex & " and " & $ruleIndex
        )
      ownerByPointer[pointer] = ruleIndex
      let location = matchesByPointer[pointer]
      let rule = result.rules[ruleIndex]
      result.descriptors.add OverlayDescriptor(
        jsonPointer: pointer,
        schemaName: descriptorSchemaName(location.segments),
        propertyName: descriptorPropertyName(location.segments),
        semantic: rule.semantic,
        representation: rule.representation,
        reason: rule.reason,
        ruleIndex: ruleIndex,
      )

  result.descriptors.sort(proc(
      left, right: OverlayDescriptor
  ): int = cmp(left.jsonPointer, right.jsonPointer))

proc findProjectRoot(start: string): string =
  var candidate = start.absolutePath
  while true:
    if fileExists(candidate / "schemas" / "schema-lock.json"):
      return candidate
    let parent = candidate.parentDir
    if parent == candidate:
      break
    candidate = parent

